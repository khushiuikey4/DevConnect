const mongoose = require('mongoose');
const devSchema = mongoose.Schema({
    userName: {
        type: String,
        required: true,
        unique: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
});
const Dev = mongoose.model('Dev', devSchema);
module.exports = Dev;